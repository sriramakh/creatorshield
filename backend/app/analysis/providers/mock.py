"""MOCK provider for UI development and tests.

It performs NO analysis. It returns one clearly-labelled placeholder finding
so the pipeline and dashboard can be exercised without an API key. Analyses
produced with it are flagged ``mock_mode=True`` and the UI and report show a
prominent "MOCK - not a real AI analysis" banner.
"""

from __future__ import annotations

from app.analysis.prompt import PromptPayload
from app.analysis.providers.base import ProviderResult
from app.schemas import AIAnalysisOutput, AIEvidence, AIFinding


class MockProvider:
    name = "mock"
    model = "mock"

    def analyze(self, payload: PromptPayload) -> ProviderResult:
        output = AIAnalysisOutput(
            summary=(
                "MOCK MODE: no AI model was called. This placeholder exists only to test the "
                "pipeline and user interface. Configure an AI provider for a real review."
            ),
            context_assessment="MOCK MODE: context was not assessed.",
            findings=[
                AIFinding(
                    category="community_guidelines",
                    finding_type="suspected_violation",
                    severity="info",
                    confidence="low",
                    title="[MOCK] Placeholder AI finding - not a real assessment",
                    explanation="Generated by the mock provider. It says nothing about the video.",
                    evidence=[
                        AIEvidence(source="metadata", ref_id="METADATA", detail="mock placeholder")
                    ],
                    start_seconds=None,
                    end_seconds=None,
                    policy_rule_ids=[],
                    suggested_action="Configure ANTHROPIC_API_KEY (or another provider) to run "
                    "the real AI review.",
                    context_exception=None,
                    requires_human_review=True,
                )
            ],
            unassessable=["MOCK MODE: AI review not performed."],
            embedded_instructions_detected=False,
        )
        return ProviderResult(output=output, provider="mock", model="mock", is_mock=True)
